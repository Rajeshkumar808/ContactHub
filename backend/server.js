require('dotenv').config();
const express=require('express');
const cors=require('cors');
const mongoose=require('mongoose');
const passport=require('passport');
const rateLimit=require('express-rate-limit');
require('./config/passport');
const authRoutes=require('./routes/authRoutes');
const contactRoutes=require('./routes/contactRoutes');
const app=express();
app.use("/api/admin", require("./routes/adminRoutes"));
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173',credentials:true}));
app.use(express.json({limit:'20kb'}));
app.use(passport.initialize());
app.use('/api/auth',rateLimit({windowMs:15*60*1000,max:100,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api/contacts',contactRoutes);
app.get('/api/health',(req,res)=>res.json({status:'ok',database:mongoose.connection.readyState===1?'connected':'disconnected'}));
app.use((err,req,res,next)=>{console.error(err);res.status(err.status||500).json({message:err.message||'Server error'});});
const port=process.env.PORT||5000;
mongoose.connect(process.env.MONGO_URI).then(()=>{console.log('MongoDB connected');app.listen(port,()=>console.log(`ContactHub API listening on ${port}`));}).catch(e=>{console.error('MongoDB connection failed:',e.message);process.exit(1);});
